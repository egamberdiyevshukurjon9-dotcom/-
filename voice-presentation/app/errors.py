"""Фойдаланувчи ўзи ҳал қила оладиган хатолар (хабари тушунарли бўлиши керак)."""


class SetupError(Exception):
    """Умумий созлаш хатоси: кутубхона, модель, созлама."""


class AudioError(SetupError):
    """Микрофон очилмади ёки ишламаяпти."""


class EngineError(SetupError):
    """Овозни таниш мотори ишга тушмади."""
